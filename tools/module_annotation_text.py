"""Inventory GuicedEE-owned annotation text and guard the reviewed surface against drift.

This is a declaration inventory, not a Java semantic analyzer. Runtime consumer checks
live in benchmarks/tools/module-annotation-contract and the focused Maven regressions.
"""
from pathlib import Path
import json
import re
import sys

SITE = Path(__file__).resolve().parents[1]
FRAMEWORK = SITE.parent
CHECK = '--check' in sys.argv
EXCLUDED = {'services', 'examples', 'website', 'website-backend', 'website-backend-jlink',
            'microprofile-tck', 'intellij-plugin', 'native-image'}
RESERVED = {'inject/InjectLogger.level', 'inject/InjectLogger.fileName', 'inject/InjectLogger.rollingFileName'}
annotations, modules, rows = {}, {}, []
for module in sorted(FRAMEWORK.iterdir()):
    root = module / 'src/main/java'
    if module.name in EXCLUDED or not root.exists():
        continue
    modules[module.name] = 0
    for source in sorted(root.rglob('*.java')):
        text = source.read_text(encoding='utf-8-sig')
        # Keep quoted literals intact while excluding documentation examples and comments.
        text = re.sub(r'"(?:\\.|[^"\\])*"|/\*.*?\*/|//[^\n]*',
                      lambda m: m[0] if m[0].startswith('"') else ' ', text, flags=re.S)
        declaration = re.search(r'@interface\s+(\w+)', text)
        if not declaration:
            continue
        members = re.findall(r'\bString(\s*\[\s*\])?\s+(\w+)\s*\(\s*\)\s*(?:default\s+[^;]+)?;', text)
        if not members:
            continue
        annotation = module.name + '/' + declaration[1]
        annotations[annotation] = [name + ('[]' if array else '') for array, name in members]
        modules[module.name] += len(members)
        for array, name in members:
            member = annotation + '.' + name
            status = ('reserved metadata; no built-in consumer' if member in RESERVED else
                      'literal configuration key identifier' if member == 'client/EnvironmentProperty.name' else
                      'shared resolver at the configuration consumer')
            rows.append(dict(module=module.name, annotation=declaration[1], member=name,
                             type='String[]' if array else 'String', status=status,
                             source=str(source.relative_to(FRAMEWORK.parent)).replace('\\', '/')))

reviewed = SITE / 'docs/configuration/module-annotation-text-reviewed.json'
if json.loads(reviewed.read_text()) != annotations:
    raise SystemExit('Annotation text surface changed: review the new/deleted members and update module-annotation-text-reviewed.json.')

def write(relative, content):
    path = SITE / relative
    if CHECK:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            raise SystemExit('Generated annotation inventory differs: ' + relative)
    else:
        path.write_text(content, encoding='utf-8')

contract = dict(scope='GuicedEE-owned runtime annotation declarations; external annotation contracts retain their semantics.',
                modules=modules, annotations=len(annotations), text_members=len(rows), members=rows)
write('docs/configuration/module-annotation-text.json', json.dumps(contract, indent=2) + '\n')
java = ['package com.guicedee.website.pages;', '', '/** Generated by tools/module_annotation_text.py. */',
        'final class AnnotationTextCatalog {', '    private AnnotationTextCatalog() {}',
        '    static String[][] rows() { return new String[][] {']
for module, count in modules.items():
    status = 'Shared lookup at consumers' if count else 'No owned String annotation members'
    if module == 'inject': status += '; three reserved logger hints'
    if module == 'client': status += '; EnvironmentProperty.name is a literal key'
    java.append('        {' + ', '.join(json.dumps(v) for v in [module, str(count), status]) + '},')
java += ['    }; }', '}', '']
write('src/main/java/com/guicedee/website/pages/AnnotationTextCatalog.java', '\n'.join(java))
print(('Verified' if CHECK else 'Generated') + f' {len(rows)} text members in {len(annotations)} annotations across {len(modules)} runtime modules')
